# ── Main system prompt ────────────────────────────────────────────────────────
_SYSTEM = """You are an expert AI creative director for a mobile advertising agency.

Analyse the user's request, any working image, and any reference images provided.
Return a JSON directive that classifies the operation and provides all parameters needed.

OPERATION TYPES:
  "remove"         → delete a specific element, fill with background
  "replace"        → swap one element for another
  "logo_placement" → place a reference logo/image onto the working image
  "style_change"   → change visual style while preserving composition
  "generate"       → create a new image from scratch
  "edit_text"      → change specific text in the image
  "edit"           → general edit that doesn't fit the above categories

RETURN VALID JSON ONLY (no markdown fence):
{
  "operation": "<one of the types above>",
  "target": "<what to affect — element name, position, or style>",
  "source": "<what to remove/replace (if applicable)>",
  "position": "<placement position for logo_placement: top-left | top-center | top-right | bottom-left | bottom-center | bottom-right | center>",
  "target_style": "<style description for style_change>",
  "source_text": "<original text for edit_text>",
  "target_text": "<replacement text for edit_text>",
  "enhanced_prompt": "<detailed visual prompt embedding the appropriate op-template constraints>",
  "preserve_elements": ["<list of elements that must NOT change>"],
  "change_elements": ["<list of what to modify>"],
  "style_description": "<art style of the working image>",
  "reasoning": "<≤30 word explanation>"
}

CRITICAL RULES (apply to ALL operations):
• Never change elements not listed in change_elements.
• Never stretch, warp, or distort any element.
• Brand logo and CTA must be legible and visible in all output sizes.
• Logo fidelity: if a reference logo image is provided and operation is logo_placement,
  signal it as logo_placement so the pipeline uses direct compositing instead of AI redraw.
"""

# ── Public functions ──────────────────────────────────────────────────────────

async def orchestrate(
    user_prompt: str,
    reference_assets: list[Asset],
    session_history: list[dict],
    target_sizes: list[str],
    static_dir: Path,
    upload_dir: Path,
    api_key: str | None,
    logo_assets: list[Asset] | None = None,
) -> dict:
    """
    Classify the user's intent and return an enhanced directive.

    logo_assets: extra reference images that the user likely intends as logos
    to composite (distinct from style-reference images).
    """
    if not api_key:
        return _passthrough(user_prompt)

    try:
        from openai import AsyncOpenAI
        client = AsyncOpenAI(api_key=api_key)

        # The orchestrator (GPT-4o) needs to know ALL target sizes to generate
        # a proper style/layout directive.  The image generation model is kept
        # away from the full size list via the contact-sheet path or
        # _single_size_prompt_text — orchestrator context is separate.
        size_note = f"Target ad sizes: {', '.join(target_sizes)}" if target_sizes else ""

        logo_note = (
            f"\n\nNOTE: {len(logo_assets)} reference image(s) provided as potential logos for placement."
            if logo_assets else ""
        )

        user_content: list[dict] = [{
            "type": "text",
            "text": f"{user_prompt}\n\n{size_note}{logo_note}".strip()
        }]

        # Attach working image references (style / content context)
        for asset in reference_assets[:3]:
            _attach_image(user_content, asset, static_dir, upload_dir, "working/reference image")

        # Attach logo images separately so the model knows they're for compositing
        if logo_assets:
            for asset in logo_assets[:2]:
                _attach_image(user_content, asset, static_dir, upload_dir, "logo/brand image to place")

        messages: list[dict] = [{"role": "system", "content": _SYSTEM}]
        messages.extend(session_history[-4:])
        messages.append({"role": "user", "content": user_content})

        # Try preferred model, fall back to gpt-4o on 404/model-not-found
        result = await _call_model(client, messages, _ORCHESTRATOR_MODEL)
        if result is None:
            logger.warning("gpt-5.4 unavailable, falling back to gpt-4o")
            result = await _call_model(client, messages, _ORCHESTRATOR_FALLBACK)
        if result is None:
            return _passthrough(user_prompt)

        logger.info("Orchestrator: op=%s reason=%s", result.get("operation"), result.get("reasoning", "")[:60])
        return result

    except Exception as exc:
        logger.warning("Orchestrator failed (%s) — pass-through", exc)
        return _passthrough(user_prompt)


async def auto_detect_and_mask(
    image_bytes: bytes,
    element_description: str,
    api_key: str,
) -> "bytes | None":
    """
    Use the vision model to locate a named element in the image, then generate
    a precise rectangular mask PNG (transparent = edit zone).

    Works well for rectangular UI elements (buttons, logos, text overlays).
    Falls back gracefully if element is not found.
    """
    from openai import AsyncOpenAI
    from PIL import Image, ImageDraw
    import io

    client = AsyncOpenAI(api_key=api_key)
    b64 = base64.b64encode(image_bytes).decode()

    detect_prompt = f"""
Look carefully at this image.
Find the element described as: "{element_description}"

Return ONLY valid JSON (no markdown):
{{
  "found": true | false,
  "confidence": "high" | "medium" | "low",
  "bbox": {{
    "x_pct": <left edge, 0-1 fraction of image width>,
    "y_pct": <top edge, 0-1 fraction of image height>,
    "w_pct": <width, 0-1 fraction of image width>,
    "h_pct": <height, 0-1 fraction of image height>
  }},
  "description": "<what you found>"
}}

If not found, return {{"found": false}}.
Be precise — err on the side of a slightly larger bbox rather than missing part of the element.
"""

    try:
        resp = await client.chat.completions.create(
            model=_DETECT_MODEL,
            messages=[{"role": "user", "content": [
                {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}", "detail": "high"}},
                {"type": "text", "text": detect_prompt},
            ]}],
            response_format={"type": "json_object"},
            max_completion_tokens=250,
            temperature=0,
        )

        # Fall back to gpt-4o when the primary request fails.
    except Exception as exc:
        logger.warning("Model %s failed in auto_detect_and_mask: %s", _DETECT_MODEL, exc)
        try:
            from openai import AsyncOpenAI as _C
            _cl = _C(api_key=api_key)
            resp = await _cl.chat.completions.create(
                model=_ORCHESTRATOR_FALLBACK,
                messages=[{"role": "user", "content": [
                    {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}", "detail": "high"}},
                    {"type": "text", "text": detect_prompt},
                ]}],
                response_format={"type": "json_object"},
                max_completion_tokens=250,
                temperature=0,
            )
        except Exception as exc2:
            logger.warning("auto_detect_and_mask failed: %s", exc2)
            return None

    try:
        data = json.loads(resp.choices[0].message.content or "{}")
    except Exception:
        return None

    if not data.get("found"):
        logger.info("auto_detect: '%s' not found in image", element_description)
        return None

    bbox = data.get("bbox", {})
    logger.info("auto_detect: '%s' at bbox=%s confidence=%s",
                element_description, bbox, data.get("confidence"))

    # Build mask PNG from bbox
    img = Image.open(io.BytesIO(image_bytes))
    w, h = img.size

    x  = int(bbox.get("x_pct", 0) * w)
    y  = int(bbox.get("y_pct", 0) * h)
    bw = int(bbox.get("w_pct", 0) * w)
    bh = int(bbox.get("h_pct", 0) * h)

    # 5% padding for cleaner inpainting
    pad_x = max(4, int(bw * 0.05))
    pad_y = max(4, int(bh * 0.05))
    x1, y1 = max(0, x - pad_x), max(0, y - pad_y)
    x2, y2 = min(w, x + bw + pad_x), min(h, y + bh + pad_y)

    mask = Image.new("RGBA", (w, h), (255, 255, 255, 255))  # opaque = preserve
    ImageDraw.Draw(mask).rectangle([x1, y1, x2, y2], fill=(0, 0, 0, 0))  # transparent = edit zone

    buf = __import__("io").BytesIO()
    mask.save(buf, format="PNG")
    return buf.getvalue()


async def detect_layout_anchors(
    image_bytes: bytes,
    api_key: str | None,
    hints: list[str] | None = None,
) -> list[dict]:
    """
    Detect visually important ad anchors in a single vision call.

    Returns normalized bounding boxes for anchor-aware resizing:
    logo, CTA button, headline block, main character face/head, and main product.
    """
    if not api_key:
        return []

    from openai import AsyncOpenAI

    client = AsyncOpenAI(api_key=api_key)
    b64 = base64.b64encode(image_bytes).decode()
    hint_text = ", ".join(hints or [])

    detect_prompt = f"""
Look carefully at this ad creative and detect only clearly visible layout anchors.

Priority hints from the generation system: {hint_text or "none"}.

Return ONLY valid JSON:
{{
  "anchors": [
    {{
      "type": "logo" | "cta" | "headline_block" | "character_face" | "character_head" | "product",
      "label": "<short description>",
      "confidence": "high" | "medium" | "low",
      "required": true,
      "bbox": {{
        "x_pct": <left edge 0-1>,
        "y_pct": <top edge 0-1>,
        "w_pct": <width 0-1>,
        "h_pct": <height 0-1>
      }}
    }}
  ]
}}

Rules:
- Only include anchors you can localize precisely.
- For character_face or character_head, capture the full face/head area so resize logic does not cut it.
- For cta, detect the primary button or strong call-to-action badge only.
- For headline_block, detect the main readable copy block or headline region.
- For logo, detect the main brand mark or wordmark only.
- For product, detect the main packshot or hero product only.
- If an anchor is absent, do not include it.
"""

    async def _call(model: str):
        return await client.chat.completions.create(
            model=model,
            messages=[{"role": "user", "content": [
                {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}", "detail": "high"}},
                {"type": "text", "text": detect_prompt},
            ]}],
            response_format={"type": "json_object"},
            max_completion_tokens=450,
            temperature=0,
        )

    try:
        resp = await _call(_DETECT_MODEL)
    except Exception:
        try:
            resp = await _call(_ORCHESTRATOR_FALLBACK)
        except Exception as exc:
            logger.warning("detect_layout_anchors failed: %s", exc)
            return []

    try:
        data = json.loads(resp.choices[0].message.content or "{}")
    except Exception:
        return []

    anchors: list[dict] = []
    allowed_types = {"logo", "cta", "headline_block", "character_face", "character_head", "product"}
    for item in data.get("anchors", []):
        bbox = item.get("bbox") or {}
        kind = str(item.get("type") or "").strip().lower()
        if kind not in allowed_types:
            continue
        try:
            x_pct = max(0.0, min(1.0, float(bbox.get("x_pct", 0.0))))
            y_pct = max(0.0, min(1.0, float(bbox.get("y_pct", 0.0))))
            w_pct = max(0.0, min(1.0, float(bbox.get("w_pct", 0.0))))
            h_pct = max(0.0, min(1.0, float(bbox.get("h_pct", 0.0))))
        except (TypeError, ValueError):
            continue
        if w_pct <= 0 or h_pct <= 0:
            continue
        anchors.append(
            {
                "type": kind,
                "label": item.get("label") or kind,
                "confidence": item.get("confidence") or "medium",
                "required": bool(item.get("required", True)),
                "bbox": {
                    "x_pct": x_pct,
                    "y_pct": y_pct,
                    "w_pct": w_pct,
                    "h_pct": h_pct,
                },
            }
        )

    return anchors


def build_operation_prompt(directive: dict, target_size: str = "1200x628") -> str:
    """
    Build a strongly-constrained prompt from the orchestrator directive,
    using the operation-specific template.
    """
    op = directive.get("operation", "edit")
    template = _OP_PROMPTS.get(op, _OP_PROMPTS["generate"])

    from app.incept.prompt_builder import get_composition_rule
    composition_rule = get_composition_rule(target_size)

    try:
        filled = template.format(
            target=directive.get("target", ""),
            source=directive.get("source", ""),
            position=directive.get("position", "top-left"),
            target_style=directive.get("target_style", ""),
            source_text=directive.get("source_text", ""),
            target_text=directive.get("target_text", ""),
            prompt=directive.get("enhanced_prompt", ""),
            target_size=target_size,
            composition_rule=composition_rule,
        )
    except KeyError:
        filled = directive.get("enhanced_prompt", "")

    return filled.strip()


# ── Internal helpers ──────────────────────────────────────────────────────────

def _attach_image(
    content: list[dict],
    asset: Asset,
    static_dir: Path,
    upload_dir: Path,
    role_label: str,
) -> None:
    """Encode asset image as base64 and append to the content list."""
    img_path = _resolve(asset.preview_url, static_dir, upload_dir)
    if not img_path or not img_path.exists():
        return
    try:
        raw = img_path.read_bytes()
        b64 = base64.b64encode(raw).decode()
        mime = "image/gif" if asset.type == "gif" else "image/png"
        content.append({"type": "text", "text": f"[{role_label}]"})
        content.append({"type": "image_url", "image_url": {
            "url": f"data:{mime};base64,{b64}", "detail": "high"
        }})
    except Exception as exc:
        logger.warning("Could not attach image %s: %s", asset.id, exc)


def _resolve(preview_url: str, static_dir: Path, upload_dir: Path) -> "Path | None":
    if preview_url.startswith("/static/generated/"):
        return static_dir / preview_url[len("/static/generated/"):]
    if preview_url.startswith("/static/uploads/"):
        return upload_dir / preview_url[len("/static/uploads/"):]
    return None


async def _call_model(client, messages: list[dict], model: str) -> "dict | None":
    """Try calling the model; return parsed JSON or None on failure."""
    try:
        resp = await client.chat.completions.create(
            model=model,
            messages=messages,
            response_format={"type": "json_object"},
            max_completion_tokens=800,
            temperature=0.2,
        )
        return json.loads(resp.choices[0].message.content or "{}")
    except Exception as exc:
        logger.warning("Model %s failed: %s", model, exc)
        return None


def _passthrough(prompt: str) -> dict:
    return {
        "operation": "edit",
        "enhanced_prompt": prompt,
        "target": "",
        "source": "",
        "position": "",
        "preserve_elements": [],
        "change_elements": [],
        "style_description": "",
        "reasoning": "orchestrator unavailable — using raw prompt",
    }

"""
Orchestration layer — upgraded to gpt-5.4 with operation-type-specific prompting.

Operations and their routing:
  remove        → auto-detect element → mask → images.edit (fill with background)
  replace       → auto-detect element → mask → images.edit (replace with target)
  logo_placement→ Pillow direct composite (pixel-perfect logo, no AI redraw)
  style_change  → images.edit full-image (style only, composition locked)
  generate      → images.generate (new image from scratch)
  outpaint      → Pillow pad + mask → images.edit
  add_text      → Pillow text overlay (no AI needed)

Falls back gracefully if API key is missing or call fails.
"""

from __future__ import annotations

import base64
import json
import logging
from pathlib import Path

from app.incept.models import Asset

logger = logging.getLogger(__name__)

# ── Model selection ───────────────────────────────────────────────────────────
# gpt-5.4 has better vision + instruction-following than gpt-4o.
# Fall back to gpt-4o if 5.4 is unavailable (the orchestrate() fn handles this).
_ORCHESTRATOR_MODEL  = "gpt-5.4"
_ORCHESTRATOR_FALLBACK = "gpt-4o"
_DETECT_MODEL        = "gpt-5.4"   # also used for element bounding-box detection


import assert from "node:assert/strict";
import { gridTiles, canvasPoint, pushEdit, validateImageDimensions, validateEncodedImage, stagedImageRecovery } from "../packages/nodeScaffold/src/imageEditing.ts";

const tiles = gridTiles(11, 7, 3, 4);
assert.equal(tiles.length, 12);
assert.equal(tiles.reduce((sum, tile) => sum + tile.width * tile.height, 0), 77);
assert.equal(tiles.at(-1).x + tiles.at(-1).width, 11);
assert.equal(tiles.at(-1).y + tiles.at(-1).height, 7);
for (const tile of tiles) assert.ok(tile.width > 0 && tile.height > 0);
for (const args of [[10, 10, 0, 3], [10, 10, 9, 3], [2, 2, 3, 1], [10, 10, 1.5, 2]]) assert.throws(() => gridTiles(...args));
assert.throws(() => validateImageDimensions(8193, 1));
assert.throws(() => validateImageDimensions(5000, 5000));
assert.throws(() => validateImageDimensions(0, 1));
assert.deepEqual(canvasPoint(35, 45, { left: 10, top: 20, width: 100, height: 100 }, 1000, 500), { x: 250, y: 125 });
assert.deepEqual(canvasPoint(-1, 1000, { left: 0, top: 0, width: 100, height: 100 }, 100, 100), { x: 0, y: 100 });
assert.deepEqual(pushEdit(["a", "b", "c"], 1, "d"), { history: ["a", "d"], cursor: 2 });
assert.deepEqual(pushEdit(["a", "b"], 2, "c", 2), { history: ["b", "c"], cursor: 2 });
const png = new Uint8Array(24); png.set([137, 80, 78, 71], 0); png.set([73, 72, 68, 82], 12);
const header = new DataView(png.buffer); header.setUint32(16, 1920); header.setUint32(20, 1080);
assert.deepEqual(validateEncodedImage(png.buffer, "image/png"), { width: 1920, height: 1080 });
header.setUint32(16, 20000); assert.throws(() => validateEncodedImage(png.buffer, "image/png"));
assert.throws(() => validateEncodedImage(new ArrayBuffer(0), "image/jpeg"));
const jpeg = Uint8Array.from([255, 216, 255, 192, 0, 7, 8, 0, 10, 0, 20]);
assert.deepEqual(validateEncodedImage(jpeg.buffer, "image/jpeg"), { width: 20, height: 10 });
const webp = new Uint8Array(30); webp.set(Buffer.from("RIFF"), 0); webp.set(Buffer.from("WEBPVP8X"), 8);
new DataView(webp.buffer).setUint32(16, 10, true); webp[24] = 19; webp[27] = 9;
assert.deepEqual(validateEncodedImage(webp.buffer, "image/webp"), { width: 20, height: 10 });
assert.deepEqual(stagedImageRecovery(["new-a", "new-b"], false), { cleanup: ["assets/new-a", "assets/new-b"], warning: "" });
const uncertain = stagedImageRecovery(["new-a"], true);
assert.deepEqual(uncertain.cleanup, []);
assert.ok(uncertain.warning.includes("assets/new-a") && uncertain.warning.includes("重复计费"));
assert.deepEqual(stagedImageRecovery([], true), { cleanup: [], warning: "" });
console.log("Image editing helper tests passed");
